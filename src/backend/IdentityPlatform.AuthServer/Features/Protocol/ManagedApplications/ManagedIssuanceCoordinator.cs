using IdentityPlatform.Infrastructure.Features.ProtocolStorage;
using IdentityPlatform.Infrastructure.Features.ProtocolTransport;
using Microsoft.AspNetCore;
using OpenIddict.Server;

namespace IdentityPlatform.AuthServer.Features.Protocol.ManagedApplications;

/// <summary>Runs native managed issuance in a transactionless response child until early durable consumption finishes.</summary>
internal sealed class ManagedIssuanceCoordinator(IServiceScopeFactory factory)
{
    private static readonly object Key = new();

    /// <summary>Claims actual native endpoint handoff, then retains every generated byte through commit and real cleanup.</summary>
    internal async ValueTask RunAsync(OpenIddictServerEvents.ProcessSignInContext context)
    {
        var http = context.Transaction.GetHttpRequest()!.HttpContext;
        var original = ProtocolStorageAmbient.Current!.Request;
        var decision = ManagedEndpointDecision.Claim(http, context);
        var result = await ProtocolResponseChild.RunAsync(http, factory, async (scope, response, token) =>
        {
            await using var issuance = new ManagedIssuance(scope, context);
            context.Transaction.SetProperty(typeof(ManagedIssuance).FullName!, issuance);
            try
            {
                var native = scope.Services.GetRequiredService<OpenIddictServerDispatcher>();
                await ProtocolStorageDispatch.RunAsync(scope.Owner, () => context.CancellationToken,
                    current => context.CancellationToken = current, () => native.DispatchAsync(context));
                if (!context.IsRequestHandled || context.IsRejected || context.IsRequestSkipped)
                {
                    throw ProtocolStorageOwner.Unavailable();
                }
                await response.SealAsync();
                await issuance.CommitAsync(token);
                return true;
            }
            finally
            {
                context.Transaction.SetProperty<ManagedIssuance>(typeof(ManagedIssuance).FullName!, null);
                context.Transaction.SetProperty<ManagedIssuanceProof>(typeof(ManagedIssuanceProof).FullName!, null);
            }
        });
        var output = result.Output ?? throw ProtocolStorageOwner.Unavailable();
        await output.CopyAndSealParentAsync(context.CancellationToken);
        http.Items.Add(Key, new Publication(original, context, decision, output));
    }

    /// <summary>Consumes the separate managed permit once only after actual native completion and every child has disposed.</summary>
    internal static bool Claim(HttpContext http, OpenIddictServerEvents.ProcessRequestContext outer)
    {
        if (!http.Items.Remove(Key, out var value))
        {
            return false;
        }
        if (value is not Publication permit || !ReferenceEquals(permit.Request, ProtocolStorageAmbient.Current?.Request) ||
            !ReferenceEquals(outer.Transaction, permit.Context.Transaction) || !permit.Decision.Allows(permit.Context))
        {
            throw ProtocolStorageOwner.Unavailable();
        }
        permit.Output.RequireFrozenParent();
        permit.Request.RequirePublication(ProtocolResponseOutcome.Committed);
        return true;
    }

    /// <summary>Retains only original native identities and frozen bytes after actual child cleanup.</summary>
    private sealed record Publication(ProtocolStorageRequest Request, OpenIddictServerEvents.ProcessSignInContext Context,
        ManagedEndpointDecision Decision, ProtocolResponseOutput Output);
}

/// <summary>Opens fresh managed authority after actual native redemption and internal-claim restoration.</summary>
internal sealed class OpenManagedIssuance : IOpenIddictServerHandler<OpenIddictServerEvents.ProcessSignInContext>
{
    /// <summary>Touches only the privately coordinated managed issuance path.</summary>
    public ValueTask HandleAsync(OpenIddictServerEvents.ProcessSignInContext context) => ManagedIssuance.Find(context.Transaction)?.OpenAsync(context.CancellationToken) ?? ValueTask.CompletedTask;
}

/// <summary>Reserves exact managed native row deltas after the installed generation evaluator.</summary>
internal sealed class ReserveManagedIssuance : IOpenIddictServerHandler<OpenIddictServerEvents.ProcessSignInContext>
{
    /// <summary>Rejects unsupported output before the first native authorization or token create.</summary>
    public ValueTask HandleAsync(OpenIddictServerEvents.ProcessSignInContext context) => ManagedIssuance.Find(context.Transaction)?.ReserveAsync(context.CancellationToken) ?? ValueTask.CompletedTask;
}

/// <summary>Bounds prepared native principals before any cryptographic output is created.</summary>
internal sealed class BoundManagedIssuance : IOpenIddictServerHandler<OpenIddictServerEvents.ProcessSignInContext>
{
    /// <summary>Preserves native preparation and clamps only its already finite expiration.</summary>
    public ValueTask HandleAsync(OpenIddictServerEvents.ProcessSignInContext context)
    {
        ManagedIssuance.Find(context.Transaction)?.Bound();
        return ValueTask.CompletedTask;
    }
}
