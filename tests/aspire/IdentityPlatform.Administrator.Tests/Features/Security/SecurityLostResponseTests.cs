using System.Net;
using IdentityPlatform.Administrator.Tests.Fixtures;
using IdentityPlatform.Infrastructure.Persistence;
using Microsoft.Extensions.DependencyInjection;

namespace IdentityPlatform.Administrator.Tests.Features.Security;

/// <summary>Checks lost one-time code responses for both replacement and regeneration without receiving any HTTP response bytes.</summary>
[Collection("administrator-bootstrap")]
public sealed class SecurityLostResponseTests(BootstrapFixture fixture)
{
    private const string ReplacementEvent = "administrator-replacement";
    private const string RegenerationEvent = "administrator-regeneration";
    private const string ProviderTrait = "Provider";
    private static readonly string[] Providers = ["PostgreSql", "SqlServer"];
    private static readonly bool[] Modes = [false, true];

    /// <summary>Exercises both one-time response owners independently on both supported production databases.</summary>
    public static IEnumerable<TheoryDataRow<string, bool>> Cases => from provider in Providers
                                                                    from replacement in Modes
                                                                    select new TheoryDataRow<string, bool>(provider, replacement).WithTrait(ProviderTrait, provider);

    /// <summary>Committed codes cannot be redisplayed or regenerated by retry; only an explicit fresh login with an unused factor works.</summary>
    [Theory, MemberData(nameof(Cases))]
    public async Task Given_UnreceivedSecurityCompletion_When_CommitSurvivesTransportLoss_Then_ReplayPreservesCodesAndFreshLoginIsRequired(string provider, bool replacement)
    {
        await using var environment = await AdministratorEnvironment.CreateAsync(fixture, provider);
        var cookies = new CookieContainer();
        using var browser = environment.Browser(cookies);
        var enrolled = await SecurityHttp.EnrollAsync(environment, browser);
        var prepared = await PrepareAsync(environment, browser, enrolled, replacement);
        await using var scope = environment.Database.Administrator.CreateAsyncScope();
        var database = scope.ServiceProvider.GetRequiredService<PlatformDbContext>();
        string committed;
        await using (var transport = new UnreceivedResponse())
        {
            await transport.SendAsync(environment.Issuer, cookies, prepared.Form, prepared.Code,
                replacement ? SecurityHttp.Confirm : SecurityHttp.Regenerate);
            await SecurityCommit.ObserveAsync(database, replacement ? ReplacementEvent : RegenerationEvent);
            committed = await SecurityCommit.RecoveryDigestAsync(database);
        }
        using var other = environment.Browser(cookies, secondary: true);
        using var denied = await other.GetAsync(AdministratorJourney.Security, TestContext.Current.CancellationToken);
        Assert.Equal(HttpStatusCode.Unauthorized, denied.StatusCode);
        using var replay = await AdministratorJourney.ConfirmAtAsync(other, prepared.Form, prepared.Code,
            replacement ? SecurityHttp.Confirm : SecurityHttp.Regenerate);
        Assert.Equal(replacement ? HttpStatusCode.BadRequest : HttpStatusCode.Unauthorized, replay.StatusCode);
        Assert.Equal(committed, await SecurityCommit.RecoveryDigestAsync(database));
        var login = await AdministratorJourney.BeginAsync(environment, other, enrollment: false);
        var form = await AdministratorJourney.ReadAsync(other, login, enrollment: false);
        var unused = FactorOracle.UnusedCode(prepared.Seed, new HashSet<string>([prepared.Code, enrolled.AcceptedCode], StringComparer.Ordinal));
        using var accepted = await AdministratorJourney.ConfirmAsync(other, form, unused, enrollment: false);
        Assert.Equal(HttpStatusCode.Redirect, accepted.StatusCode);
        Assert.Equal(committed, await SecurityCommit.RecoveryDigestAsync(database));
    }

    /// <summary>Uses restricted recovery for replacement so its first replacement audit is the completion witness, not a prior voluntary staging audit.</summary>
    private static async Task<PreparedSecurity> PrepareAsync(AdministratorEnvironment environment, HttpClient browser, SecurityEnrollment enrolled, bool replacement)
    {
        var initial = await AdministratorJourney.BeginAtAsync(environment, browser, replacement ? SecurityHttp.Recovery : SecurityHttp.Regeneration);
        var form = await AdministratorJourney.ReadAsync(browser, initial, enrollment: false);
        if (!replacement)
        {
            return new PreparedSecurity(form, enrolled.Seed, FactorOracle.UnusedCode(enrolled.Seed, enrolled.AcceptedCode));
        }
        var location = await SecurityHttp.TransitionAsync(browser, form, enrolled.RecoveryCodes[0], recovery: true);
        var confirmation = await AdministratorJourney.ReadAsync(browser, location, enrollment: true);
        return new PreparedSecurity(confirmation, confirmation.Seed!, FactorOracle.Code(confirmation.Seed!, DateTimeOffset.UtcNow.ToUnixTimeSeconds()));
    }
}

/// <summary>Keeps a prepared synthetic proof in memory without a generated secret-bearing textual representation.</summary>
internal sealed class PreparedSecurity(AdministratorForm form, string seed, string code)
{
    internal AdministratorForm Form { get; } = form;
    internal string Seed { get; } = seed;
    internal string Code { get; } = code;
}
