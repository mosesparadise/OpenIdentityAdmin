using IdentityPlatform.CodeQuality.Features.Analysis;
using IdentityPlatform.CodeQuality.Features.Evidence;

namespace IdentityPlatform.CodeQuality.Features.Verification;

/// <summary>Exercise real parsed source and evidence boundaries with independent positive and negative controls.</summary>
internal static class RuleControls
{
    private const string TestPath = "tests/Probe.cs";
    private const string ConditionalHelper = "public partial class Probe : Migration { protected override void Up(MigrationBuilder builder) {} protected override void Down(MigrationBuilder builder) {} }\n#if DEBUG\ninternal class Helper { void Hidden() {} }\n#endif";
    private const string OneLocal = "internal class Probe { void Run() { if (ready) { void Local() { Call(42); } } } }";
    private const string TwoLocals = "internal class Probe { void Run() { if (ready) { void Local() { Call(42); } } else { void Local() { Call(42); } } } }";
    private const string LocalIdentity = ".Local()";
    private const string GenericCanary = "internal class Probe { void Run<[Probe(\"synthetic-canary\")] T>() {} }";
    private const string Canary = "synthetic-canary";
    private const string Conditional = "#if UNSELECTED\ninternal class Probe { void Hidden() {} }\n#endif";
    private const string Partial = "internal partial class Probe {}";
    private const string GeneratedPath = "src/migrations/IdentityPlatform.Migrations.PostgreSql/Platform/20261012110309_Probe.cs";
    private const string Generated = "public partial class Probe : Migration { protected override void Up(MigrationBuilder builder) {} protected override void Down(MigrationBuilder builder) {} }";
    private const string FakeGenerated = "// <auto-generated />\ninternal class Helper { void Undocumented() {} }";
    private const string SourcePath = "src/Probe.cs";
    private static readonly string[] EmptyScenarioParts = ["Given__When_action_Then_result", "Given_state_When__Then_result", "Given_state_When_action_Then_"];
    private const string Failure = "A seeded code-quality control did not produce its expected outcome.";
    private const string Accepted = "PASS: scenario, XML, public example, size, literal and allowance controls.";
    private const string Clean = "internal class Probe { /// <summary>Describe the expected observed result.</summary>\n[Fact] public void Given_valid_input_When_checked_Then_result_matches() { Assert.Equal(42, actual); } }";
    private const string BadName = "internal class Probe { [Fact] public void Unclear() {} }";
    private const string Aliased = "using Case = Xunit.FactAttribute; internal class Probe { [Case] public void Unclear() {} }";
    private const string ScopedAliases = "namespace A { using Case = Xunit.FactAttribute; class Probe { [Case] public void Bad() {} } } namespace B { using Case = Xunit.TheoryAttribute; class Probe { [Case] public void Bad() {} } }";
    private const string Utf8Unnamed = "internal class Probe { void Run() { Send(\"policy\"u8); } }";
    private const string Utf8Named = "internal class Probe { static readonly byte[] Policy = \"policy\"u8.ToArray(); }";
    private const string Custom = "internal class Probe { [CustomCase] public void Unclear() {} }";
    private const string Qualified = "internal class Probe { [global::Xunit.TheoryAttribute] public void Unclear() {} }";
    private const string EmptyXml = "internal class Probe { /// <summary/>\nvoid Run() {} }";
    private const string MalformedXml = "internal class Probe { /// <summary>Broken\nvoid Run() {} }";
    private const string EmptyExample = "/// <summary>Reusable parser.</summary><example/>\npublic class Probe {}";
    private const string GoodExample = "/// <summary>Reusable parser.</summary><example><code>var value = new Probe();</code></example>\npublic class Probe {}";
    private const string Unnamed = "internal class Probe { /// <summary>Apply the configured retry limit.</summary>\nvoid Run() { Call(42); } }";
    private const string Named = "internal class Probe { const int RetryLimit = 42; /// <summary>Apply the configured retry limit.</summary>\nvoid Run() { Call(RetryLimit); } }";
    private const string StringTrap = "internal class Probe { const string Text = \"[Fact] void BadName() { Call(42); }\"; }";
    private const string MethodStart = "internal class Probe { /// <summary>Exercise repeated operations.</summary>\nvoid Run() {\n";
    private const string MethodEnd = "} }";
    private const string Statement = "Call();\n";
    private const string TaskId = "T014";
    private const string Owner = "Implementation lead";
    private const string Reason = "Synthetic test of bounded exception expiry.";
    private const string FingerprintChange = "changed";
    private const int LongMethodLines = 45;
    private const int LongClassLines = 305;
    private const int MethodBoundaryStatements = 39;
    private const int TypeBoundaryStatements = 298;
    private const string WideNumber = "internal class Probe { const double Limit = 1e100; }";
    private const string PreciseNumber = "internal class Probe { void Run() { Call(1.0000000000000000001m); } }";
    private const int Year = 2026;
    private const int Month = 10;
    private const int Day = 12;

    /// <summary>Run deterministic gate controls; a failed expectation terminates the tool with failure.</summary>
    internal static void Run()
    {
        Given_valid_source_When_inspected_Then_no_findings();
        Given_invalid_source_When_inspected_Then_each_rule_rejects();
        Given_exact_legacy_When_changed_or_stale_Then_allowance_rejects();
        Given_scoped_exception_When_expired_Then_allowance_rejects();
        Given_source_edge_cases_When_scanned_Then_no_silent_exemptions_or_literal_leaks();
        Given_exact_size_boundaries_When_one_line_added_Then_gate_rejects();
        Console.WriteLine(Accepted);
    }

    /// <summary>Prove that independent expected values, named constants and source-like strings are not defects.</summary>
    private static void Given_valid_source_When_inspected_Then_no_findings()
    {
        foreach (var source in new[] { Clean, Named, StringTrap, Utf8Named })
        {
            Require(SyntaxRules.Inspect(TestPath, source).Count == 0);
        }
        Require(SyntaxRules.Inspect(SourcePath, GoodExample).Count == 0);
        foreach (var name in EmptyScenarioParts)
        {
            Require(!SyntaxRules.IsScenario(name));
        }
    }

    /// <summary>Reject bad names and documentation plus boundary-crossing sizes and unnamed operational values.</summary>
    private static void Given_invalid_source_When_inspected_Then_each_rule_rejects()
    {
        foreach (var source in new[] { BadName, Aliased, Qualified, Custom, ScopedAliases })
        {
            Expect(source, SyntaxRules.ScenarioRule);
        }

        foreach (var source in new[] { BadName, EmptyXml, MalformedXml })
        {
            Expect(source, SyntaxRules.MethodDocumentationRule);
        }

        Require(SyntaxRules.Inspect(SourcePath, EmptyExample).Any(finding => finding.Rule == SyntaxRules.PublicDocumentationRule));
        Expect(Unnamed, SyntaxRules.LiteralRule);
        Expect(Utf8Unnamed, SyntaxRules.LiteralRule);
        Expect(MethodStart + string.Concat(Enumerable.Repeat(Statement, LongMethodLines)) + MethodEnd, SyntaxRules.MethodSizeRule);
        Expect(MethodStart + string.Concat(Enumerable.Repeat(Statement, LongClassLines)) + MethodEnd, SyntaxRules.TypeSizeRule);
    }

    /// <summary>Reject changed fingerprints, duplicate allowances and stale entries, while accepting unchanged debt.</summary>
    private static void Given_exact_legacy_When_changed_or_stale_Then_allowance_rejects()
    {
        var finding = SyntaxRules.Inspect(TestPath, BadName)[0];
        var entry = new LegacyEntry(finding, TaskId, Owner);
        var today = new DateOnly(Year, Month, Day);
        Allowances.Validate(new([entry], []), [finding], today);
        Reject(() => Allowances.Validate(new([entry, entry], []), [finding], today));
        Reject(() => Allowances.Validate(new([entry], []), [], today));
        Reject(() => Allowances.Validate(new([entry], []), [finding with { Fingerprint = FingerprintChange }], today));
    }

    /// <summary>Accept only still-valid reviewed exceptions with exact current evidence and populated ownership.</summary>
    private static void Given_scoped_exception_When_expired_Then_allowance_rejects()
    {
        var finding = SyntaxRules.Inspect(TestPath, BadName)[0];
        var today = new DateOnly(Year, Month, Day);
        var entry = new ExceptionEntry(finding, TaskId, Owner, Reason, today.AddDays(1));
        Allowances.Validate(new([], [entry]), [finding], today);
        Reject(() => Allowances.Validate(new([], [entry with { Expires = today }]), [finding], today));
        Reject(() => Allowances.Validate(new([], [entry with { Owner = string.Empty }]), [finding], today));
        Reject(() => Allowances.Validate(new([], [entry with { Reason = string.Empty }]), [finding], today));
    }

    /// <summary>Prove conditional/partial source requires review and false generator labels or generic attributes do not bypass controls.</summary>
    private static void Given_source_edge_cases_When_scanned_Then_no_silent_exemptions_or_literal_leaks()
    {
        Require(SyntaxRules.Inspect(SourcePath, GenericCanary).All(finding => !finding.Symbol.Contains(Canary, StringComparison.Ordinal)));
        Expect(Conditional, SyntaxRules.ConditionalRule);
        Expect(Partial, SyntaxRules.PartialRule);
        Require(GeneratedArtifacts.Matches(GeneratedPath, Generated));
        Require(!GeneratedArtifacts.Matches(GeneratedPath, FakeGenerated));
        Require(!GeneratedArtifacts.Matches(SourcePath, Generated));
        Require(!GeneratedArtifacts.Matches(GeneratedPath, ConditionalHelper));
        var original = SyntaxRules.Inspect(SourcePath, OneLocal).Where(finding => finding.Symbol.EndsWith(LocalIdentity, StringComparison.Ordinal)).ToArray();
        var copied = SyntaxRules.Inspect(SourcePath, TwoLocals).Where(finding => finding.Symbol.EndsWith(LocalIdentity, StringComparison.Ordinal)).ToArray();
        Require(original.Length > 0 && copied.Length > 0 && !original.Intersect(copied).Any());
    }

    /// <summary>Prove the approved exact size thresholds and native numeric precision independently of rule constants.</summary>
    private static void Given_exact_size_boundaries_When_one_line_added_Then_gate_rejects()
    {
        var method = MethodStart + string.Concat(Enumerable.Repeat(Statement, MethodBoundaryStatements)) + MethodEnd;
        Require(!SyntaxRules.Inspect(TestPath, method).Any(finding => finding.Rule == SyntaxRules.MethodSizeRule));
        Expect(MethodStart + string.Concat(Enumerable.Repeat(Statement, MethodBoundaryStatements + 1)) + MethodEnd, SyntaxRules.MethodSizeRule);
        var type = MethodStart + string.Concat(Enumerable.Repeat(Statement, TypeBoundaryStatements)) + MethodEnd;
        Require(!SyntaxRules.Inspect(TestPath, type).Any(finding => finding.Rule == SyntaxRules.TypeSizeRule));
        Expect(MethodStart + string.Concat(Enumerable.Repeat(Statement, TypeBoundaryStatements + 1)) + MethodEnd, SyntaxRules.TypeSizeRule);
        Require(SyntaxRules.Inspect(TestPath, WideNumber).Count == 0);
        Expect(PreciseNumber, SyntaxRules.LiteralRule);
    }

    /// <summary>Assert a specific independent rule identifier appears in parsed source findings.</summary>
    private static void Expect(string source, string rule) => Require(SyntaxRules.Inspect(TestPath, source).Any(finding => finding.Rule == rule));

    /// <summary>Require a negative evidence control to fail with the documented validation exception.</summary>
    private static void Reject(Action action)
    {
        try
        {
            action();
        }
        catch (InvalidDataException) { return; }
        throw new InvalidOperationException(Failure);
    }

    /// <summary>Fail a seeded control without serializing synthetic source or candidate literals.</summary>
    private static void Require(bool condition)
    {
        if (!condition)
        {
            throw new InvalidOperationException(Failure);
        }
    }
}
